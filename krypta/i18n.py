_RAW = {'en': EN,'pl': PL,'ru': RU,'zh': ZH,'es': ES,'ar': AR,'hi': HI,'pt': PT,'fr': FR,'de': DE,'id': ID}
for lang, entries in _RAW.items():
    if len(entries) != len(FIELDS):
        raise ValueError(f'Incomplete translation {lang}: {len(entries)} vs {len(FIELDS)}')
    if not all(isinstance(item, str) and item.strip() for item in entries):
        raise ValueError(f'Empty translation in {lang}')

CATALOG = {lang: dict(zip(FIELDS, entries)) for lang, entries in _RAW.items()}


def normalize_language(tag: str | None) -> str:
    if not isinstance(tag, str):
        return 'en'
    primary = tag.replace('_', '-').split('-')[0].lower()
    return primary if primary in CATALOG else 'en'


def translate(language: str, key: str) -> str:
    if key not in CATALOG['en']:
        raise KeyError(key)
    return CATALOG[normalize_language(language)][key]