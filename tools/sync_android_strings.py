"""Generate deterministic Android language resources from KRYPTA's shared UI catalogue.

Usage: python tools/sync_android_strings.py [--check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from xml.sax.saxutils import escape
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from krypta.i18n import CATALOG, FIELDS

ANDROID = Path(__file__).resolve().parents[1] / 'android/app/src/main/res'
FOLDERS = {'en': 'values', 'pl': 'values-pl', 'ru': 'values-ru',
           'zh': 'values-zh-rCN', 'es': 'values-es', 'ar': 'values-ar',
           'hi': 'values-hi', 'pt': 'values-pt', 'fr': 'values-fr',
           'de': 'values-de', 'id': 'values-in'}


def format_android(text: str) -> str:
    # Escape reserved XML characters and Android-specific quote/backslash rules.
    return (escape(text).replace('\\', '\\\\').replace("'", "\\'")
            .replace('"', '\\"').replace('\n', '\\n'))


def render(lang: str) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<resources>',
             '    <!-- Generated by tools/sync_android_strings.py; edit krypta/i18n.py. -->']
    for key in FIELDS:
        lines.append(f'    <string name="{key}">{format_android(CATALOG[lang][key])}</string>')
    lines.append('</resources>')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    error = False
    for lang, folder in FOLDERS.items():
        target = ANDROID / folder / 'strings.xml'
        expected = render(lang)
        if args.check:
            if not target.is_file() or target.read_text(encoding='utf-8') not in (expected, expected.removesuffix('\n')):
                print('OUT OF SYNC:', target)
                error = True
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected, encoding='utf-8')
    return int(error)


if __name__ == '__main__':
    raise SystemExit(main())